/*
 * Generates the changelog page from the library's own CHANGELOG.md.
 *
 * The library keeps a Keep-a-Changelog file that is updated in the same PR as
 * the change it describes. Re-typing that here would guarantee drift -- the
 * site already documents a "v2.0.0" that was never released -- so the page is
 * generated from the single source of truth instead.
 *
 * Runs on prebuild, so a new release appears on the site without anyone
 * remembering to copy anything.
 *
 * Fails soft. A docs build should not break because GitHub is slow, so a
 * failed fetch leaves the committed page in place and warns. The generated
 * file is committed for exactly this reason: the site builds offline, and the
 * diff is reviewable.
 */
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/content/docs/reference/changelog.md');
const SOURCE =
  'https://raw.githubusercontent.com/iyashjayesh/monigo/main/CHANGELOG.md';
const REPO = 'https://github.com/iyashjayesh/monigo';
const PROXY = 'https://proxy.golang.org/github.com/iyashjayesh/monigo/@v/list';

/** A release: its version, date, and the body between headings. */
function parseReleases(markdown) {
  const lines = markdown.split('\n');
  const releases = [];
  let current = null;

  for (const line of lines) {
    // "## [1.7.0] - 2026-08-30", or "## [Unreleased]"
    const m = /^##\s+\[([^\]]+)\](?:\s+-\s+(\S+))?/.exec(line);
    if (m) {
      if (current) releases.push(current);
      current = { version: m[1], date: m[2] ?? null, body: [] };
      continue;
    }
    if (current) current.body.push(line);
  }
  if (current) releases.push(current);

  return releases
    // An empty Unreleased section is the normal state right after a release.
    .filter((r) => r.body.join('').trim().length > 0)
    .map((r) => ({ ...r, body: r.body.join('\n').trim() }));
}

/** Demote the release's own "### Added" to "####" so the page's own
 *  "## v1.7.0" headings stay the top level in the sidebar's table of contents. */
function demote(body) {
  return body.replace(/^### /gm, '#### ');
}

/* Which versions the module proxy will actually serve.
 *
 * The library's CHANGELOG carries a v2.0.0 section dated 2026-02-10. That tag
 * exists in git but was never published: its go.mod declares the v1 module
 * path, so the proxy rejects it and `go get ...@v2.0.0` fails. Listing it
 * unqualified would send readers after a version they cannot install -- the
 * same confusion this page exists to clear up.
 *
 * Fails soft: on a fetch error every version renders unqualified, which is the
 * behaviour before this check existed.
 */
async function installableVersions() {
  try {
    const res = await fetch(PROXY, { signal: AbortSignal.timeout(15_000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const text = await res.text();
    return new Set(
      text.split('\n').map((v) => v.trim().replace(/^v/, '')).filter(Boolean)
    );
  } catch (err) {
    console.warn(
      '[changelog] could not read the module proxy ' +
        `(${err instanceof Error ? err.message : err}); ` +
        'rendering every version unqualified.'
    );
    return null;
  }
}

/** Newest first, by version rather than by position in the file. */
function bySemverDesc(a, b) {
  if (a.version === 'Unreleased') return -1;
  if (b.version === 'Unreleased') return 1;
  const pa = a.version.split('.').map(Number);
  const pb = b.version.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    if ((pb[i] ?? 0) !== (pa[i] ?? 0)) return (pb[i] ?? 0) - (pa[i] ?? 0);
  }
  return 0;
}

function anchor(version) {
  return 'v' + version.replace(/\./g, '-').toLowerCase();
}

function render(releases, installable) {
  const front = [
    '---',
    'title: Changelog',
    'description: Every released version of MoniGo, what changed in it, and why.',
    'tableOfContents:',
    '  maxHeadingLevel: 2',
    '---',
    '',
    '<!-- Generated by scripts/sync-changelog.mjs from the library CHANGELOG.md.',
    '     Do not edit by hand: prebuild overwrites it. -->',
    '',
    'Every released version, newest first. Taken directly from the library’s',
    `[CHANGELOG.md](${REPO}/blob/main/CHANGELOG.md), which is updated in the same`,
    'pull request as the change it describes.',
    '',
  ];

  const released = releases.filter(
    (r) =>
      r.version !== 'Unreleased' &&
      (!installable || installable.has(r.version))
  );
  if (released.length) {
    const latest = released[0];
    front.push(
      `The current release is **v${latest.version}**` +
        (latest.date ? ` (${latest.date})` : '') + '.',
      '',
      '```bash',
      'go get github.com/iyashjayesh/monigo@latest',
      '```',
      '',
      ''
    );
  }

  const sections = releases.map((r) => {
    const unpublished =
      r.version !== 'Unreleased' && installable && !installable.has(r.version);
    const alreadyFlagged = /never published/i.test(r.body);
    const heading =
      r.version === 'Unreleased'
        ? '## Unreleased'
        : `## v${r.version}` + (r.date ? ` — ${r.date}` : '');
    const link =
      r.version === 'Unreleased'
        ? `[Compare against the latest release](${REPO}/compare/v${released[0]?.version ?? 'main'}...main)`
        : `[Release notes](${REPO}/releases/tag/v${r.version})`;
    const note = unpublished && !alreadyFlagged
      ? [
          '',
          ':::caution[Never published]',
          `v${r.version} was tagged but never released: the tag is not on the Go`,
          'module proxy, so `go get` cannot resolve it. The changes below reached',
          'users through the v1 releases instead.',
          ':::',
        ].join('\n')
      : '';
    const body = [heading, note, '', demote(r.body), ''];
    if (!unpublished) body.push(link, '');
    return body.join('\n');
  });

  return front.join('\n') + sections.join('\n---\n\n') + '\n';
}

async function main() {
  let markdown;
  try {
    const res = await fetch(SOURCE, { signal: AbortSignal.timeout(20_000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    markdown = await res.text();
  } catch (err) {
    // Soft failure: keep whatever is committed.
    let existing = false;
    try {
      await readFile(OUT, 'utf8');
      existing = true;
    } catch {}
    const detail = err instanceof Error ? err.message : String(err);
    if (existing) {
      console.warn(
        `[changelog] could not fetch CHANGELOG.md (${detail}); ` +
          'keeping the committed page.'
      );
      return;
    }
    throw new Error(
      `[changelog] could not fetch CHANGELOG.md (${detail}) and no committed ` +
        'page exists to fall back on.'
    );
  }

  const releases = parseReleases(markdown).sort(bySemverDesc);
  const installable = await installableVersions();
  if (releases.length === 0) {
    throw new Error('[changelog] parsed zero releases — the source format changed?');
  }

  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, render(releases, installable), 'utf8');

  // Report the newest INSTALLABLE version, not simply the highest number --
  // an unpublished tag sorts first and would misreport the release in CI logs.
  const named = releases.filter(
    (r) => r.version !== 'Unreleased' && (!installable || installable.has(r.version))
  );
  const skipped = releases.filter(
    (r) => r.version !== 'Unreleased' && installable && !installable.has(r.version)
  );
  console.log(
    `[changelog] wrote ${releases.length} sections, ` +
      `latest installable v${named[0]?.version ?? '?'}` +
      (skipped.length ? ` (${skipped.map((r) => 'v' + r.version).join(', ')} not on the proxy)` : '')
  );
}

main().catch((err) => {
  console.error(err.message ?? err);
  process.exit(1);
});
